#!/bin/bash
# =============================================
# 脚本名称: grep_pra.sh
# 功能描述: 过滤错误日志，剔除空行和注释行（grep练习）
# 作者: Jasyn
# 版本: 2.0
# 用法: ./grep_pra.sh [日志文件] [-h]
# 示例: ./grep_pra.sh app.log
# 输出: 控制台显示过滤结果
# =============================================

# =============================================
# 函数定义
# =============================================

# 显示帮助信息
show_help() {
    cat << EOF
用法: $0 [日志文件] [选项]

选项:
  -h, --help             显示此帮助信息

示例:
  $0 app.log             过滤 app.log 文件中的错误日志并剔除空行/注释行
  $0 /var/log/error.log  指定完整路径

说明:
  脚本会执行以下过滤操作：
  1. 查找所有包含 "error" 或 "ERROR" 的行（不区分大小写）
  2. 剔除所有空行（^$）
  3. 剔除所有以 # 开头的注释行（^#）
EOF
    exit 0
}

# =============================================
# 解析命令行参数
# =============================================

# 默认日志文件
FILE="app.log"

# 手动解析参数（支持第一个参数为文件名）
for arg in "$@"; do
    case $arg in
        -h|--help)
            show_help
            ;;
        -*)
            # 忽略其他选项
            ;;
        *)
            # 第一个非选项参数作为文件名
            if [ -z "$FILE" ] || [ "$FILE" = "app.log" ]; then
                FILE="$arg"
            fi
            ;;
    esac
done

# =============================================
# 主程序
# =============================================

# 检查日志文件是否存在
if [ ! -f "$FILE" ]; then
    echo "错误：日志文件 $FILE 不存在"
    echo "用法: $0 [日志文件]"
    exit 1
fi

echo "================================"
echo "日志文件: $FILE"
echo "================================"
echo ""

echo "【1. 过滤错误日志（不区分大小写）】"
echo "--------------------------------"
grep -i 'error' "$FILE" 2>/dev/null
if [ $? -ne 0 ]; then
    echo "（未找到 error 关键字）"
fi
echo ""

echo "【2. 剔除空行和注释行】"
echo "--------------------------------"
echo "方式一：组合过滤（grep -v 链式）"
grep -v '^$' "$FILE" 2>/dev/null | grep -v '^#'
echo ""
echo "方式二：扩展正则（grep -E 一次性过滤）"
grep -E -v '^$|^#' "$FILE" 2>/dev/null
echo ""

echo "【3. 同时过滤错误日志 + 剔除空行和注释行】"
echo "--------------------------------"
grep -i 'error' "$FILE" 2>/dev/null | grep -v '^$' | grep -v '^#'
echo ""

echo "================================"
echo "过滤完成"
echo "================================"

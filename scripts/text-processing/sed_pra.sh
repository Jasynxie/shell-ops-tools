#!/bin/bash
# =============================================
# 脚本名称: sed_pra.sh
# 功能描述: 批量修改配置、清理空行和注释行（sed练习）
# 作者: Jasyn
# 版本: 2.0
# 用法: ./sed_pra.sh [配置文件] [-h]
# 示例: ./sed_pra.sh app.conf
# 输出: 控制台显示修改前后的对比
# =============================================

# =============================================
# 函数定义
# =============================================

# 显示帮助信息
show_help() {
    cat << EOF
用法: $0 [配置文件] [选项]

选项:
  -h, --help             显示此帮助信息

示例:
  $0 app.conf            处理 app.conf 配置文件

说明:
  脚本会执行以下操作：
  1. 备份原始配置文件（*.original）
  2. 删除所有空行和以 # 开头的注释行
  3. 批量修改配置参数（如端口号、连接数等）
  4. 显示修改前后的对比
EOF
    exit 0
}

# =============================================
# 解析命令行参数
# =============================================

# 默认配置文件
FILE="app.conf"

# 手动解析参数（支持第一个参数为文件名）
for arg in "$@"; do
    case $arg in
        -h|--help)
            show_help
            ;;
        -*)
            # 忽略其他选项
            ;;
        *)
            # 第一个非选项参数作为文件名
            if [ -z "$FILE" ] || [ "$FILE" = "app.conf" ]; then
                FILE="$arg"
            fi
            ;;
    esac
done

# =============================================
# 主程序
# =============================================

# 检查配置文件是否存在
if [ ! -f "$FILE" ]; then
    echo "错误：配置文件 $FILE 不存在"
    echo "用法: $0 [配置文件]"
    exit 1
fi

# 定义备份文件名
FILE_ORIGINAL="${FILE}.original"

echo "================================"
echo "配置文件: $FILE"
echo "================================"
echo ""

# 1. 查看原始配置文件
echo "【1. 原始配置文件内容】"
echo "--------------------------------"
cat -n "$FILE"
echo ""

# 2. 备份原始文件
echo "【2. 备份原始文件】"
echo "--------------------------------"
cp "$FILE" "$FILE_ORIGINAL"
echo "已备份到: $FILE_ORIGINAL"
echo ""

# 3. 清理空行和注释行
echo "【3. 清理空行和注释行】"
echo "--------------------------------"
# 方式1：使用 sed 多次编辑
sed -i '/^$/d' "$FILE"
sed -i '/^#/d' "$FILE"
echo "已删除空行和注释行（分步执行）"
echo ""

# 4. 批量修改配置参数
echo "【4. 批量修改配置参数】"
echo "--------------------------------"
# 使用 -e 多次编辑，一次完成多个替换
sed -i \
    -e 's/8080/9090/g' \
    -e 's/MAX_CONNECTIONS=100/MAX_CONNECTIONS=500/g' \
    -e 's/DB_PASS=123456/DB_PASS=********/g' \
    "$FILE"
echo "已修改配置参数："
echo "  - 端口: 8080 → 9090"
echo "  - 最大连接数: 100 → 500"
echo "  - 数据库密码: 123456 → ********（已脱敏）"
echo ""

# 5. 查看修改后的配置文件
echo "【5. 修改后的配置文件内容】"
echo "--------------------------------"
cat -n "$FILE"
echo ""

echo "================================"
echo "修改完成"
echo "原始备份: $FILE_ORIGINAL（未改动）"
echo "修改后文件: $FILE"
echo "================================"

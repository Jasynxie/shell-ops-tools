#!/bin/bash
# =============================================
# 脚本名称: awk_pra.sh
# 功能描述: 统计访问IP、筛选高使用率磁盘分区（awk练习）
# 作者: Jasyn
# 版本: 2.0
# 用法: ./awk_pra.sh [选项] [-h]
# 示例: ./awk_pra.sh
# 输出: 控制台显示统计结果
# =============================================

# =============================================
# 函数定义
# =============================================

# 显示帮助信息
show_help() {
    cat << EOF
用法: $0 [选项]

选项:
  -h, --help             显示此帮助信息

示例:
  $0                     使用默认的 access.log 进行练习

说明:
  脚本会执行以下操作：
  1. 统计 access.log 中每个IP的访问次数（按次数倒序排列）
  2. 筛选磁盘使用率超过指定阈值（默认20%）的分区
  3. 显示当前磁盘使用情况
EOF
    exit 0
}

# =============================================
# 解析命令行参数
# =============================================
while getopts "h" opt; do
    case $opt in
        h) show_help ;;
        *) show_help ;;
    esac
done

# =============================================
# 创建示例日志文件（如果不存在）
# =============================================
if [ ! -f "access.log" ]; then
    echo "创建示例日志文件 access.log ..."
    cat > access.log << EOF
192.168.1.100 - - [10/Aug/2026:10:00:00 +0800] "GET /index.html" 200 1024
192.168.1.101 - - [10/Aug/2026:10:00:05 +0800] "GET /api/users" 200 2048
192.168.1.100 - - [10/Aug/2026:10:00:10 +0800] "GET /index.html" 200 1024
192.168.1.102 - - [10/Aug/2026:10:00:15 +0800] "POST /api/login" 200 512
192.168.1.103 - - [10/Aug/2026:10:00:20 +0800] "GET /about.html" 404 0
192.168.1.101 - - [10/Aug/2026:10:00:25 +0800] "GET /api/users" 200 2048
192.168.1.100 - - [10/Aug/2026:10:00:30 +0800] "GET /dashboard" 200 3072
192.168.1.104 - - [10/Aug/2026:10:00:35 +0800] "GET /index.html" 200 1024
192.168.1.102 - - [10/Aug/2026:10:00:40 +0800] "POST /api/logout" 200 256
192.168.1.100 - - [10/Aug/2026:10:00:45 +0800] "GET /api/users" 200 2048
EOF
    echo "示例日志文件创建完成"
    echo ""
fi

# =============================================
# 主程序
# =============================================

echo "================================"
echo "        awk 实战练习"
echo "================================"
echo ""

# =============================================
# 练习1：统计访问IP
# =============================================
echo "【练习1：统计每个IP的访问次数】"
echo "--------------------------------"

# 检查 access.log 是否存在
if [ ! -f "access.log" ]; then
    echo "错误：access.log 不存在"
    exit 1
fi

echo "访问日志前5行预览："
head -5 access.log
echo ""

echo "IP访问次数统计（按访问量倒序排列）："
echo "访问次数 | IP地址"
echo "---------|---------"
awk '{print $1}' access.log | sort | uniq -c | sort -rn | while read count ip; do
    printf "  %-7s | %s\n" "$count" "$ip"
done
echo ""

# =============================================
# 练习2：筛选高使用率磁盘分区
# =============================================
echo "【练习2：筛选高使用率磁盘分区】"
echo "--------------------------------"

# 设置阈值，默认20%
THRESHOLD=20

echo "当前磁盘使用情况："
df -h
echo ""

echo "使用率超过 ${THRESHOLD}% 的分区："
echo "--------------------------------"
df -h | awk -v threshold="$THRESHOLD" '
    NR==1 {print $0; print "--------------------------------"; next}
    {
        # 提取使用率（第5列），去掉 % 符号
        gsub(/%/, "", $5)
        if ($5+0 > threshold) {
            print $0 "  ← 超过阈值 " threshold "%"
        }
    }
'
echo ""

echo "================================"
echo "练习完成"
echo "================================"

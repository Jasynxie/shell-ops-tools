#!/bin/bash
# =============================================
# 脚本名称: Yange_pattern.sh
# 功能描述: 演示生产环境脚本的严格模式与错误处理规范
# 作者: Jasyn
# 版本: 2.0
# 用法: ./Yange_pattern.sh [-h]
# 示例: ./Yange_pattern.sh
# 输出: 控制台显示执行过程和结果
# =============================================

# =============================================
# 严格模式（生产环境脚本必备）
# =============================================
set -e          # 命令执行失败时立即退出
set -u          # 使用未定义变量时立即退出
set -o pipefail # 管道中任何命令失败都算整体失败

# =============================================
# 函数定义
# =============================================

# 显示帮助信息
show_help() {
    cat << EOF
用法: $0 [选项]

选项:
  -h, --help             显示此帮助信息

示例:
  $0                     运行脚本，演示严格模式和错误处理

说明:
  本脚本用于演示以下生产环境编码规范：
  1. set -e: 命令失败立即退出
  2. set -u: 变量未定义立即退出
  3. set -o pipefail: 管道中任何命令失败都算失败
  4. error_exit: 自定义错误处理函数
  5. 变量检查: 使用前检查是否为空
  6. 条件执行: 使用 || 或 && 控制流程
EOF
    exit 0
}

# 自定义错误处理函数
error_exit() {
    echo "错误: $1" >&2
    exit 1
}

# =============================================
# 解析命令行参数
# =============================================
while getopts "h" opt; do
    case $opt in
        h) show_help ;;
        *) show_help ;;
    esac
done

# =============================================
# 主程序
# =============================================

echo "================================"
echo "    严格模式 + 错误处理演示"
echo "================================"
echo ""
echo "【当前脚本配置】"
echo "  set -e          : 命令失败立即退出"
echo "  set -u          : 变量未定义立即退出"
echo "  set -o pipefail : 管道命令失败即失败"
echo ""

# =============================================
# 演示1：检查变量是否为空
# =============================================
echo "【演示1：变量检查】"
echo "--------------------------------"

read -p "请输入要检测的路径: " dir_path

# 检查是否输入了路径（-z 判断字符串是否为空）
if [ -z "$dir_path" ]; then
    error_exit "路径不能为空"
fi

echo "你输入的路径是: $dir_path"
echo ""

# =============================================
# 演示2：目录检测与创建
# =============================================
echo "【演示2：目录检测与创建】"
echo "--------------------------------"

if [ -d "$dir_path" ]; then
    echo "目录 '$dir_path' 已存在"
else
    echo "目录 '$dir_path' 不存在，正在创建..."
    # 如果 mkdir 失败，error_exit 会被调用
    mkdir -p "$dir_path" || error_exit "目录创建失败，请检查权限"
    echo "目录创建成功"
fi
echo ""

# =============================================
# 演示3：文件操作（展示 set -e 的效果）
# =============================================
echo "【演示3：文件操作】"
echo "--------------------------------"

# 创建一个测试文件
TEST_FILE="./test_$(date +%Y%m%d_%H%M%S).txt"
echo "Hello, this is a test file." > "$TEST_FILE"
echo "已创建测试文件: $TEST_FILE"

# 读取文件内容
echo "文件内容:"
cat "$TEST_FILE"
echo ""

# 演示：如果文件不存在，cat 会失败，脚本立即退出
# 但这里我们故意用安全的写法
echo "尝试读取不存在的文件（展示 set -e 的效果）..."
if [ -f "./not_exist_file.txt" ]; then
    cat "./not_exist_file.txt"
else
    echo "（文件不存在，跳过，脚本继续执行）"
fi
echo ""

# =============================================
# 演示4：管道命令中的错误处理
# =============================================
echo "【演示4：管道命令（set -o pipefail）】"
echo "--------------------------------"

echo "执行管道命令: ls /nonexist | wc -l"
# 由于 set -o pipefail，如果 ls 失败，脚本会退出
# 这里我们用 || true 来演示但避免脚本退出
if ls /nonexist 2>/dev/null | wc -l >/dev/null 2>&1; then
    echo "管道命令执行成功"
else
    echo "管道命令执行失败（符合预期，展示 pipefail 的效果）"
fi
echo ""

# =============================================
# 演示5：未定义变量（展示 set -u 的效果）
# =============================================
echo "【演示5：未定义变量（set -u）】"
echo "--------------------------------"

echo "如果你看到这行，说明脚本还在运行。"
echo "下面演示未定义变量的情况（被注释掉了）..."

# 取消下面一行的注释，可以看到 set -u 的效果
# echo "未定义变量: $undefined_var"

echo "（未定义变量的行已被注释，脚本正常执行）"
echo ""

# =============================================
# 清理
# =============================================
echo "【清理】"
echo "--------------------------------"
if [ -f "$TEST_FILE" ]; then
    rm -f "$TEST_FILE"
    echo "已删除测试文件: $TEST_FILE"
fi
echo ""

echo "================================"
echo "脚本执行完成（所有检查通过）"
echo "================================"
